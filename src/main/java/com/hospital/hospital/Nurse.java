
public class Nurse {

    private String user;
    private String pw;
    private String name;

    public Nurse(String user, String pw) {
        this.user = user;
        this.pw = pw;
        this.name = name;
    }

    public String getUser() {
        return user;
    }
    
    public String getPw() {
        return pw;
    }
    public String getName() {
        return name;
    }
    

    
}
